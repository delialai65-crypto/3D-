CREATE TABLE IF NOT EXISTS users (
    id BIGSERIAL PRIMARY KEY,
    username VARCHAR(20) UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    level INTEGER NOT NULL DEFAULT 1,
    xp INTEGER NOT NULL DEFAULT 0,
    coins INTEGER NOT NULL DEFAULT 1000,
    rating INTEGER NOT NULL DEFAULT 0,
    wins INTEGER NOT NULL DEFAULT 0,
    losses INTEGER NOT NULL DEFAULT 0,
    tags INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS matches (
    id BIGSERIAL PRIMARY KEY,
    room_code VARCHAR(40) NOT NULL,
    blue_score INTEGER NOT NULL DEFAULT 0,
    red_score INTEGER NOT NULL DEFAULT 0,
    winner VARCHAR(10),
    duration_seconds INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS match_players (
    id BIGSERIAL PRIMARY KEY,
    match_id BIGINT NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    team VARCHAR(10) NOT NULL,
    tags INTEGER NOT NULL DEFAULT 0,
    result VARCHAR(10) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_users_rating
ON users(rating DESC, wins DESC);

CREATE INDEX IF NOT EXISTS idx_matches_created
ON matches(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_match_players_user
ON match_players(user_id);
